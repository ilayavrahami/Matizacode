// פונקציה שעמוד הניהול קורא לה כדי לטעון את השיעורים לדאטהבייס
async function loadSeedLessons() {
  const batch = db.batch();
  seedLessons.forEach((lesson) => {
    const { id, ...data } = lesson;
    batch.set(db.collection('lessons').doc(id), data);
  });
  await batch.commit();
}